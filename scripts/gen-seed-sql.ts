/**
 * Generates supabase/seed.sql from lib/seed.ts so demo mode and the database
 * start from the same data. Run: npm run seed:sql
 * The SQL wipes all catalogue tables first, so it can be re-run any time
 * (and later replaced with the client's real stock).
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  SEED_DEF_TIMING,
  SEED_PRODUCTS,
  SEED_REPAIR_PRICES,
  SEED_REVIEWS,
  SEED_SETTINGS,
  SEED_SWAP_VALUES,
} from "../lib/seed";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(",")}]::text[]` : "'{}'::text[]");

const out: string[] = [
  "-- GENERATED by scripts/gen-seed-sql.ts from lib/seed.ts. Do not edit by hand.",
  "-- Placeholder demo data: prices are rough values. Wipe and replace with real stock.",
  "begin;",
  "delete from public.variants;",
  "delete from public.products;",
  "delete from public.swap_values;",
  "delete from public.repair_prices;",
  "delete from public.reviews;",
  "delete from public.settings;",
  "",
];

SEED_PRODUCTS.forEach((p, i) => {
  const t = SEED_DEF_TIMING[i];
  const deal = t.dealHours ? `now() + interval '${Math.round(t.dealHours * 60)} minutes'` : "null";
  out.push(
    `insert into public.products (id, slug, name, brand, category, condition, description, specs, images, tags, deal_ends_at, is_active, created_at) values (${[
      q(p.id),
      q(p.slug),
      q(p.name),
      q(p.brand),
      q(p.category),
      q(p.condition),
      q(p.description),
      `${q(JSON.stringify(p.specs))}::jsonb`,
      arr(p.images),
      arr(p.tags),
      deal,
      q(p.is_active),
      `now() - interval '${t.age} days'`,
    ].join(", ")});`,
  );
  for (const v of p.variants) {
    out.push(
      `insert into public.variants (id, product_id, storage, colour, price, old_price, in_stock, stock_qty, grade, battery_health, warranty_months, notes) values (${[
        v.id,
        v.product_id,
        v.storage,
        v.colour,
        v.price,
        v.old_price,
        v.in_stock,
        v.stock_qty,
        v.grade,
        v.battery_health,
        v.warranty_months,
        v.notes,
      ]
        .map(q)
        .join(", ")});`,
    );
  }
});

out.push("");
for (const s of SEED_SWAP_VALUES) {
  out.push(
    `insert into public.swap_values (id, brand, model, storage, base_value, is_active) values (${[s.id, s.brand, s.model, s.storage, s.base_value, s.is_active].map(q).join(", ")});`,
  );
}
out.push("");
for (const r of SEED_REPAIR_PRICES) {
  out.push(
    `insert into public.repair_prices (id, brand, model, issue, price_from, duration) values (${[r.id, r.brand, r.model, r.issue, r.price_from, r.duration].map(q).join(", ")});`,
  );
}
out.push("");
SEED_REVIEWS.forEach((r, i) => {
  out.push(
    `insert into public.reviews (id, name, text, rating, area, created_at) values (${[r.id, r.name, r.text, r.rating, r.area].map(q).join(", ")}, now() - interval '${i} minutes');`,
  );
});
out.push("");
const s = SEED_SETTINGS;
out.push(
  `insert into public.settings (id, whatsapp_number, store_address, opening_hours, delivery_note, instagram_handle) values (1, ${[s.whatsapp_number, s.store_address, s.opening_hours, s.delivery_note, s.instagram_handle].map(q).join(", ")});`,
);
out.push("commit;", "");

const file = join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file}`);
